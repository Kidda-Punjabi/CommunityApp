export function emojiForIcon(iconName: string | null | undefined): string {
  if (!iconName?.trim()) return "❓";
  const key = iconName.trim().toLowerCase();
  return emojiMap[key] ?? "❓";
}

export function hasEmojiIcon(iconName: string | null | undefined): boolean {
  if (!iconName?.trim()) return false;
  return iconName.trim().toLowerCase() in emojiMap;
}

/** Match English prompt text (e.g. "sun / sunshine") to an emoji-map icon key. */
export function deriveIconFromEnglish(english: string): string | null {
  const normalized = english.trim().toLowerCase();
  if (!normalized) return null;

  const firstSegment = normalized.split("/")[0]?.trim() ?? "";
  const firstWord = firstSegment.split(/\s+/)[0] ?? "";

  if (emojiMap[firstWord]) return firstWord;
  if (emojiMap[firstSegment]) return firstSegment;
  if (emojiMap[normalized]) return normalized;
  return null;
}
